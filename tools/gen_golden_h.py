"""Converts tests/golden.json (reference vectors) into tests/golden.h for the C tests."""
import json
import os
import sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(root, "tests", "golden.json")
dst = sys.argv[2] if len(sys.argv) > 2 else os.path.join(root, "tests", "golden.h")
g = json.load(open(src))
out = ["/* generated by tools/gen_golden_h.py from golden.json — do not edit */",
       "#define AD_GOLDEN_CASES %d" % len(g["cases"]),
       "typedef struct { double w, h, density, font_scale; int mw; double f[12][44]; double k_scaled, k_auto; } ad_golden_case;",
       "static const ad_golden_case ad_golden[AD_GOLDEN_CASES] = {"]
for c in g["cases"]:
    rows = ",".join("{" + ",".join(repr(x) for x in c["factors"][s]) + "}" for s in g["strategies"])
    out.append("  {%r,%r,%r,%r,%d,{%s},%r,%r}," % (c["w"], c["h"], c["density"], c["fontScale"],
               1 if c["multiWindow"] else 0, rows, c["customK001"]["scaled"], c["customK001"]["auto"]))
out.append("};")
open(dst, "w").write("\n".join(out) + "\n")
print(dst)
